# --- end to end, over HTTP, against the reference connector ---------------


async def test_end_to_end_against_the_reference_connector(tmp_path, monkeypatch):
    """Proves the whole contract: a real signed request, a real signature
    verification on the other side, and a real transcript coming back.

    This is what catches URL re-encoding — if httpx normalised `%3A` back to
    `:`, the path signed and the path verified would differ and this 401s.
    """
    monkeypatch.setenv("DATACENTER_SIGNING_SECRET", SECRET)
    monkeypatch.setenv("TRANSCRIPT_DIR", str(tmp_path))

    from contrib.datacenter_connector.main import app as connector_app

    record = {
        "meetingId": "zoom-uuid-1",
        "topic": "Phase II weekly sync",
        "hostEmail": "alice@example.com",
        "startTime": 1_736_899_200_000,
        "endTime": 1_736_902_800_000,
        "transcript": TRANSCRIPT,
        "format": "vtt",
    }
    digest = hashlib.sha256(record["meetingId"].encode()).hexdigest()
    (tmp_path / f"{digest}.json").write_text(json.dumps(record))

    client = DatacenterTranscriptClient(
        config=DatacenterConfig(base_url="http://transcripts.internal", signing_secret=SECRET),
        transport=httpx.ASGITransport(app=connector_app),
    )
    meetings = await client.fetch_range("2025-01-01T00:00:00Z", "2025-02-01T00:00:00Z")

    assert len(meetings) == 1
    assert meetings[0].topic == "Phase II weekly sync"

    result = await MeetingTranscriptsTool(client=client).run(
        MeetingTranscriptsArgs(
            query="when is the interim analysis?",
            from_time="2025-01-01T00:00:00Z",
            to_time="2025-02-01T00:00:00Z",
        )
    )
    assert "interim analysis" in result.content
    assert "Phase II weekly sync (2025-01-15)" in result.citations[0]


async def test_connector_rejects_a_bad_signature(tmp_path, monkeypatch):
    monkeypatch.setenv("DATACENTER_SIGNING_SECRET", SECRET)
    monkeypatch.setenv("TRANSCRIPT_DIR", str(tmp_path))
    from contrib.datacenter_connector.main import app as connector_app

    client = DatacenterTranscriptClient(
        config=DatacenterConfig(base_url="http://transcripts.internal", signing_secret="wrong-secret"),
        transport=httpx.ASGITransport(app=connector_app),
    )
    with pytest.raises(DatacenterError, match="rejected our signature"):
        await client.fetch_range("2025-01-01T00:00:00Z", "2025-02-01T00:00:00Z")
