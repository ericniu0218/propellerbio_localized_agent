SECRET = "test-shared-secret"

# ts, method, path_with_query, body, expected_hex — from the TypeScript implementation.
GOLDEN_VECTORS = [
    (
        1700000000000,
        "GET",
        "/transcripts?from=2026-01-01T00%3A00%3A00Z&to=2026-01-02T00%3A00%3A00Z",
        "",
        "2013313c585179799ddb44806f7fdb54097332825859b7c5347b235fdc97dc49",
    ),
    (
        1700000000000,
        "GET",
        "/transcripts/abc-123",
        "",
        "b075fe34c8a09b69be7856f025dac81090b0ede0b028a0ebbe591999efada60f",
    ),
    (
        1736899200000,
        "POST",
        "/transcripts",
        '{"meetingId":"m1"}',
        "f0f48fb292206131b96dd32ad942abe5237c34500c24eb2d0685173738eee90c",
    ),
]

TRANSCRIPT = """WEBVTT

1
00:00:01.000 --> 00:00:05.000
Alice Chen: Let's start with the Phase II enrollment numbers.

2
00:00:05.500 --> 00:00:11.000
Bob Ruiz: We're two weeks behind. Site 4 hasn't sent their paperwork.

3
00:00:11.500 --> 00:00:18.000
Alice Chen: Then we push the interim analysis to March. Bob owns chasing site 4.

4
00:00:18.500 --> 00:00:24.000
Priya Nair: I'll update the statistical analysis plan to match the new date.
"""


def _meeting(**overrides) -> MeetingTranscript:
    defaults = dict(
        meeting_id="meeting-1",
        topic="Phase II weekly sync",
        host_email="alice@example.com",
        start_time=1_736_899_200_000,  # 2025-01-15T00:00:00Z
        end_time=1_736_902_800_000,
        transcript=TRANSCRIPT,
    )
    return MeetingTranscript(**{**defaults, **overrides})


# --- signing: must agree with the Worker exactly -------------------------


@pytest.mark.parametrize("timestamp,method,path,body,expected", GOLDEN_VECTORS)
def test_signature_matches_the_worker(timestamp, method, path, body, expected):
    assert sign_request(SECRET, timestamp, method, path, body) == expected


def test_query_encoding_matches_the_documented_contract():
    # The README's worked example; colons must arrive percent-encoded, because
    # the signature covers the literal path string.
    assert transcripts_path("2026-01-01T00:00:00Z", "2026-01-02T00:00:00Z") == (
        "/transcripts?from=2026-01-01T00%3A00%3A00Z&to=2026-01-02T00%3A00%3A00Z"
    )


def test_signature_is_bound_to_method_and_path():
    """The replay protection the Worker added — a signature for one range must
    not validate another."""
    base = sign_request(SECRET, 1, "GET", "/transcripts?from=a&to=b", "")
    assert base != sign_request(SECRET, 1, "POST", "/transcripts?from=a&to=b", "")
    assert base != sign_request(SECRET, 1, "GET", "/transcripts?from=a&to=c", "")
    assert base != sign_request(SECRET, 2, "GET", "/transcripts?from=a&to=b", "")


def test_public_datacenter_url_is_refused():
    """Querying through the public relay would make the air-gapped system call
    the internet to answer a question — the thing the air gap exists to stop."""
    with pytest.raises(DatacenterError, match="air-gapped"):
        assert_internal_endpoint("https://vault.acme.workers.dev")
    assert_internal_endpoint("http://transcripts.internal:8080")  # does not raise


# --- VTT parsing ---------------------------------------------------------


def test_parses_speakers_and_timestamps():
    cues = parse_vtt(TRANSCRIPT)
    assert len(cues) == 4
    assert cues[0].speaker == "Alice Chen"
    assert cues[0].timestamp == "00:00:01"
    assert "Phase II enrollment" in cues[0].text
    assert speakers(cues) == ["Alice Chen", "Bob Ruiz", "Priya Nair"]


def test_malformed_blocks_are_skipped_not_fatal():
    cues = parse_vtt("WEBVTT\n\nNOTE this is a comment\n\ngarbage\n\n" + TRANSCRIPT)
    assert len(cues) == 4


def test_handles_crlf_transcripts():
    """Zoom writes CRLF; a stray \\r would otherwise end up inside the text."""
    cues = parse_vtt(TRANSCRIPT.replace("\n", "\r\n"))
    assert cues[0].speaker == "Alice Chen"
    assert "\r" not in cues[0].text


# --- ranking -------------------------------------------------------------


def test_ranks_the_relevant_part_of_the_meeting():
    excerpts, matched = rank_excerpts("when is the interim analysis?", [_meeting()], top_k=3)
    assert matched is True
    assert "interim analysis" in excerpts[0].render()
    assert "Phase II weekly sync (2025-01-15) @" in excerpts[0].citation


def test_unmatched_question_falls_back_without_claiming_a_match():
    excerpts, matched = rank_excerpts("quarterly travel budget", [_meeting()], top_k=3)
    assert matched is False  # caller must not present this as an answer
    assert excerpts


def test_stopwords_do_not_manufacture_matches():
    _, matched = rank_excerpts("what did we do about it", [_meeting()], top_k=3)
    assert matched is False


